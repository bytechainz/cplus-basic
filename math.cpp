#include <iostream>
#include <cmath>
using namespace std;

int main() {
    cout << "max : " << max(3,5) << endl;
    cout << "min : " << min(3,5) << endl;

    cout << "Square root of 64 is: " << sqrt(64) << "\n";
    cout << "Round 2.6 to the nearest integer: " << round(2.6) << "\n";
    cout << "The natural logarithm of 2 is: " <<log(2) << "\n";

    return 0;
}